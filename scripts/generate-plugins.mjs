import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { discoverPlugins, moduleSpecifier, publicPluginManifest } from './lib/plugin-manifests.mjs';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const generatedHeader = '// Generated by scripts/generate-plugins.mjs.\n';

async function writeChanged(path, contents) {
  try { if (await readFile(path, 'utf8') === contents) return; } catch (error) { if (error.code !== 'ENOENT') throw error; }
  await writeFile(path, contents);
}

export async function generatePluginRegistries({ pluginsDir = resolve(projectRoot, 'src/plugins'), outputDir = resolve(projectRoot, 'src/plugin-system/generated'), contractsImport = '../contracts.js' } = {}) {
  const plugins = await discoverPlugins(pluginsDir);
  const manifests = plugins.map(plugin => publicPluginManifest(plugin.manifest));
  const catalog = generatedHeader + `import type { PluginManifest } from ${JSON.stringify(contractsImport)};\n\nexport const pluginManifests: readonly PluginManifest[] = ${JSON.stringify(manifests, null, 2)};\n`;
  const consoleImports = plugins.map((plugin, index) => `import createPlugin${index} from ${JSON.stringify(moduleSpecifier(outputDir, plugin.entries.console))};`).join('\n');
  const consoleRegistry = generatedHeader + `import type { PluginDefinition } from ${JSON.stringify(contractsImport)};\nimport { pluginManifests } from './catalog.js';\n${consoleImports}\n\nexport const pluginDefinitions: readonly PluginDefinition[] = [\n${plugins.map((_plugin, index) => `  createPlugin${index}(pluginManifests[${index}]!),`).join('\n')}\n];\n`;
  const runners = plugins.filter(plugin => plugin.entries.runner);
  const runnerImports = runners.map((plugin, index) => `import { runnerDefinition as runnerDefinition${index} } from ${JSON.stringify(moduleSpecifier(outputDir, plugin.entries.runner))};`).join('\n');
  const runnerRegistry = generatedHeader + `import type { PluginRunnerDefinition } from ${JSON.stringify(contractsImport)};\n${runnerImports}\n\nexport const runnerDefinitions: readonly { pluginId: string; definition: PluginRunnerDefinition }[] = [\n${runners.map((plugin, index) => `  { pluginId: ${JSON.stringify(plugin.manifest.id)}, definition: runnerDefinition${index} },`).join('\n')}\n];\n`;
  await mkdir(outputDir, { recursive: true });
  await writeChanged(resolve(outputDir, 'catalog.ts'), catalog);
  await writeChanged(resolve(outputDir, 'console.ts'), consoleRegistry);
  await writeChanged(resolve(outputDir, 'runner.ts'), runnerRegistry);
  return { plugins: plugins.map(plugin => plugin.manifest.id), outputDir };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2), options = {};
    for (let index = 0; index < args.length; index += 2) {
      const flag = args[index], value = args[index + 1];
      if (!value || !['--plugins-dir', '--output-dir'].includes(flag)) throw new Error('Usage: generate-plugins.mjs [--plugins-dir DIRECTORY] [--output-dir DIRECTORY]');
      options[flag === '--plugins-dir' ? 'pluginsDir' : 'outputDir'] = resolve(value);
    }
    const result = await generatePluginRegistries(options);
    process.stdout.write(`Plugin registry generated: ${result.plugins.join(', ')}\n`);
  } catch (error) {
    process.stderr.write((error instanceof Error ? error.message : 'Plugin registry generation failed') + '\n');
    process.exitCode = 1;
  }
}
